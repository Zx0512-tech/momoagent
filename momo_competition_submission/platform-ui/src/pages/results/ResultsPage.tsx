import React, { useState } from "react";
import { useNavigate } from "react-router-dom";
import { CheckCircle2, Copy, FileSpreadsheet, Plus, RotateCcw, Save, Trash2 } from "lucide-react";
import { api } from "../../api/client";
import type {
  Artifact,
  ResultComponent,
  ResultExtractionMetricConfig,
  ResultObjectType,
  ResultResponseType,
  ResultStatisticType
} from "../../api/types";
import { ArtifactPreview } from "../../components/artifact/ArtifactPreview";
import { ErrorPanel } from "../../components/feedback/ErrorPanel";
import { ProgressBar } from "../../components/feedback/ProgressBar";
import { StatusBadge } from "../../components/feedback/StatusBadge";
import {
  RESULT_OBJECT_TYPE_OPTIONS,
  RESULT_RESPONSE_TYPE_OPTIONS,
  RESULT_STATISTIC_OPTIONS,
  getResultObjectTypeLabel,
  getResultResponseTypeLabel,
  getResultStatisticLabel
} from "../../api/engineeringOptions";
import { useEngineeringConfigStore } from "../../stores/engineeringConfigStore";
import { useJobStore } from "../../stores/jobStore";
import { useManagedIntervals } from "../../hooks/useManagedIntervals";
import { errorMessage } from "../../utils/errors";

const COMPONENTS: ResultComponent[] = ["UX", "UY", "UZ", "VX", "VY", "VZ", "AX", "AY", "AZ", "FX", "FY", "FZ", "MX", "MY", "MZ", "LOCAL_AXIAL"];

const createMetric = (): ResultExtractionMetricConfig => ({
  id: `metric_${Date.now()}`,
  name: "自定义结构响应",
  objectType: "NODE",
  objectId: "481",
  component: "UX",
  responseType: "DISPLACEMENT",
  statistic: "PEAK",
  enabled: true,
  autoGenerated: false,
  sourceDescription: "用户自定义结构响应"
});

export const ResultsPage: React.FC = () => {
  const navigate = useNavigate();
  const {
    resultExtractionConfig,
    updateResultExtractionConfig,
    validateModule
  } = useEngineeringConfigStore();
  const { submitJob, activeJobs, error: jobError, clearError, reportError } = useJobStore();
  const { setManagedInterval, clearManagedInterval } = useManagedIntervals();
  const [solverRunId, setSolverRunId] = useState("run_20260701_0001");
  const [currentJobId, setCurrentJobId] = useState<string | null>(null);
  const [extractedArtifacts, setExtractedArtifacts] = useState<Artifact[]>([]);
  const [selectedArtifact, setSelectedArtifact] = useState<Artifact | null>(null);

  const activeJob = currentJobId ? activeJobs[currentJobId] : null;
  const isRunning = activeJob?.status === "RUNNING" || activeJob?.status === "QUEUED";

  const updateStructuralMetric = (id: string, patch: Partial<ResultExtractionMetricConfig>) => {
    updateResultExtractionConfig({
      structuralMetrics: resultExtractionConfig.structuralMetrics.map(metric => (
        metric.id === id ? { ...metric, ...patch } : metric
      )),
      validated: false
    });
  };

  const updateDamperMetric = (id: string, enabled: boolean) => {
    updateResultExtractionConfig({
      autoDamperMetrics: resultExtractionConfig.autoDamperMetrics.map(metric => (
        metric.id === id ? { ...metric, enabled } : metric
      )),
      validated: false
    });
  };

  const addMetric = () => {
    updateResultExtractionConfig({
      structuralMetrics: [...resultExtractionConfig.structuralMetrics, createMetric()],
      validated: false
    });
  };

  const copyMetric = (metric: ResultExtractionMetricConfig) => {
    updateResultExtractionConfig({
      structuralMetrics: [
        ...resultExtractionConfig.structuralMetrics,
        { ...metric, id: `${metric.id}_copy_${Date.now()}`, name: `${metric.name} 副本`, autoGenerated: false }
      ],
      validated: false
    });
  };

  const deleteMetric = (id: string) => {
    updateResultExtractionConfig({
      structuralMetrics: resultExtractionConfig.structuralMetrics.filter(metric => metric.id !== id),
      validated: false
    });
  };

  const monitorJobResult = (jobId: string) => {
    const check = setManagedInterval(async () => {
      try {
        const job = await api.getJob(jobId);
        if (job.status === "SUCCEEDED") {
          clearManagedInterval(check);
          const arts = await api.getArtifacts({ jobId });
          setExtractedArtifacts(arts.data);
        } else if (job.status === "FAILED" || job.status === "CANCELLED") {
          clearManagedInterval(check);
        }
      } catch (error) {
        clearManagedInterval(check);
        reportError(errorMessage(error, "读取结果提取任务状态失败"));
      }
    }, 1500);
  };

  const handleSubmit = async (event: React.FormEvent) => {
    event.preventDefault();
    clearError();
    setExtractedArtifacts([]);
    validateModule("RESULT_EXTRACTION");
    const metrics = [
      ...resultExtractionConfig.structuralMetrics,
      ...resultExtractionConfig.autoDamperMetrics
    ].filter(metric => metric.enabled);
    try {
      const job = await submitJob("RESULT_EXTRACTION", {
        solverRunId,
        metrics,
        exportRawData: resultExtractionConfig.exportRawData
      });
      setCurrentJobId(job.jobId);
      monitorJobResult(job.jobId);
    } catch (error) {
      reportError(errorMessage(error, "启动结果提取失败"));
    }
  };

  return (
    <div className="page-container">
      <div style={styles.header}>
        <div>
          <h1 style={styles.title}>结果提取与报告</h1>
          <p style={styles.subtitle}>结构响应由用户配置对象和分量；阻尼器出力、行程、耗能由自动注册表生成。</p>
        </div>
        <div style={styles.headerActions}>
          <button className="btn btn-secondary" onClick={() => navigate("/")}>
            <RotateCcw size={14} />
            <span>返回主面板</span>
          </button>
          <button className="btn btn-primary" onClick={() => validateModule("RESULT_EXTRACTION")}>
            <CheckCircle2 size={14} />
            <span>校验配置</span>
          </button>
        </div>
      </div>

      <div style={styles.mainGrid}>
        <div className="panel" style={{ flex: 3 }}>
          <form onSubmit={handleSubmit}>
            <div className="panel-header">
              <span style={styles.panelTitle}>
                <FileSpreadsheet size={16} color="var(--primary-color)" />
                <span>结构响应提取配置</span>
              </span>
              <button type="button" className="btn btn-secondary" onClick={addMetric}>
                <Plus size={14} />
                <span>新增指标</span>
              </button>
            </div>

            {jobError && <ErrorPanel message={jobError} />}

            <div style={styles.formRow}>
              <div className="form-group" style={{ flex: 1 }}>
                <label className="form-label">Solver Run ID</label>
                <input className="form-control" value={solverRunId} onChange={event => setSolverRunId(event.target.value)} />
              </div>
              <label style={styles.checkItem}>
                <input
                  type="checkbox"
                  checked={resultExtractionConfig.exportRawData}
                  onChange={event => updateResultExtractionConfig({ exportRawData: event.target.checked, validated: false })}
                />
                <span>导出原始数据文件供核实</span>
              </label>
            </div>

            <MetricTable
              metrics={resultExtractionConfig.structuralMetrics}
              editable
              onChange={updateStructuralMetric}
              onCopy={copyMetric}
              onDelete={deleteMetric}
            />

            <div style={styles.sectionTitle}>阻尼器自动提取项</div>
            <div style={styles.notice}>
              以下指标来自阻尼器实例注册表。用户可控制是否输出，但节点/单元编号由模型解析或命令流组装自动维护。累计行程表示对象在整个分析阶段累计走过的位移路径，单位为 m。
            </div>
            <MetricTable
              metrics={resultExtractionConfig.autoDamperMetrics}
              editable={false}
              onToggle={updateDamperMetric}
            />

            <button className="btn btn-primary" type="submit" disabled={isRunning} style={{ marginTop: 16 }}>
              <Save size={14} />
              <span>保存并启动结果提取</span>
            </button>
          </form>
        </div>

        <div style={styles.sideColumn}>
          {currentJobId && (
            <div className="panel">
              <div className="panel-header">
                <span style={{ fontWeight: 600 }}>提取作业状态</span>
                <StatusBadge status={activeJob?.status || "QUEUED"} />
              </div>
              {isRunning ? (
                <ProgressBar
                  percent={activeJob?.progress?.percent}
                  phase={activeJob?.progress?.phase}
                  message={activeJob?.progress?.message}
                />
              ) : (
                <div style={styles.muted}>任务已结束</div>
              )}
            </div>
          )}

          <div className="panel">
            <div className="panel-header">
              <span style={{ fontWeight: 600 }}>提取输出制品</span>
            </div>
            {extractedArtifacts.length === 0 ? (
              <div style={styles.empty}>启动结果提取后，在此显示 JSON、CSV、RAW_DATA 与报告文件。</div>
            ) : (
              <div style={{ display: "flex", flexDirection: "column", gap: 8 }}>
                {extractedArtifacts.map(artifact => (
                  <button
                    key={artifact.artifactId}
                    type="button"
                    style={styles.artifactRow}
                    onClick={() => artifact.canPreview && setSelectedArtifact(artifact)}
                  >
                    <span>{artifact.name}</span>
                    <span className="badge badge-secondary">{artifact.kind}</span>
                  </button>
                ))}
              </div>
            )}
          </div>
        </div>
      </div>

      {selectedArtifact && <ArtifactPreview artifact={selectedArtifact} onClose={() => setSelectedArtifact(null)} />}
    </div>
  );
};

const MetricTable: React.FC<{
  metrics: ResultExtractionMetricConfig[];
  editable: boolean;
  onChange?: (id: string, patch: Partial<ResultExtractionMetricConfig>) => void;
  onToggle?: (id: string, enabled: boolean) => void;
  onCopy?: (metric: ResultExtractionMetricConfig) => void;
  onDelete?: (id: string) => void;
}> = ({ metrics, editable, onChange, onToggle, onCopy, onDelete }) => (
  <div style={{ overflowX: "auto" }}>
    <table className="data-table">
      <thead>
        <tr>
          <th>输出</th>
          <th>指标名称</th>
          <th>对象类型</th>
          <th>对象编号</th>
          <th>方向/分量</th>
          <th>响应类型</th>
          <th>统计方式</th>
          <th>来源</th>
          {editable && <th>操作</th>}
        </tr>
      </thead>
      <tbody>
        {metrics.map(metric => (
          <tr key={metric.id}>
            <td>
              <input
                type="checkbox"
                checked={metric.enabled}
                onChange={event => (
                  editable
                    ? onChange?.(metric.id, { enabled: event.target.checked })
                    : onToggle?.(metric.id, event.target.checked)
                )}
              />
            </td>
            <td>
              {editable ? (
                <input className="form-control" value={metric.name} onChange={event => onChange?.(metric.id, { name: event.target.value })} />
              ) : metric.name}
            </td>
            <td>
              {editable ? (
                <select className="form-control" value={metric.objectType} onChange={event => onChange?.(metric.id, { objectType: event.target.value as ResultObjectType })}>
                  {RESULT_OBJECT_TYPE_OPTIONS.map(item => <option key={item.id} value={item.id}>{item.label}</option>)}
                </select>
              ) : getResultObjectTypeLabel(metric.objectType)}
            </td>
            <td>
              {editable ? (
                <input className="form-control" value={metric.objectId} onChange={event => onChange?.(metric.id, { objectId: event.target.value })} />
              ) : <code>{metric.objectId}</code>}
            </td>
            <td>
              {editable ? (
                <select className="form-control" value={metric.component} onChange={event => onChange?.(metric.id, { component: event.target.value as ResultComponent })}>
                  {COMPONENTS.map(item => <option key={item} value={item}>{item}</option>)}
                </select>
              ) : metric.component}
            </td>
            <td>
              {editable ? (
                <select className="form-control" value={metric.responseType} onChange={event => onChange?.(metric.id, { responseType: event.target.value as ResultResponseType })}>
                  {RESULT_RESPONSE_TYPE_OPTIONS.map(item => <option key={item.id} value={item.id}>{item.label}</option>)}
                </select>
              ) : getResultResponseTypeLabel(metric.responseType)}
            </td>
            <td>
              {editable ? (
                <select className="form-control" value={metric.statistic} onChange={event => onChange?.(metric.id, { statistic: event.target.value as ResultStatisticType })}>
                  {RESULT_STATISTIC_OPTIONS.map(item => <option key={item.id} value={item.id}>{item.label}</option>)}
                </select>
              ) : getResultStatisticLabel(metric.statistic)}
            </td>
            <td style={styles.sourceCell}>{metric.sourceDescription}</td>
            {editable && (
              <td>
                <div style={styles.rowActions}>
                  <button type="button" className="btn btn-secondary" style={styles.iconBtn} onClick={() => onCopy?.(metric)} title="复制">
                    <Copy size={13} />
                  </button>
                  <button type="button" className="btn btn-secondary" style={styles.iconBtn} onClick={() => onDelete?.(metric.id)} title="删除">
                    <Trash2 size={13} />
                  </button>
                </div>
              </td>
            )}
          </tr>
        ))}
      </tbody>
    </table>
  </div>
);

