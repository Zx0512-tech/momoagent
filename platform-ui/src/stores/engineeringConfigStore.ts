export const createDamperRegistry = (
  materialType: DamperMaterialType,
  connectionNodePairs: DamperConnectionNodePair[],
  direction: DamperBaseConfig["direction"]
): DamperInstanceRegistryEntry[] => {
  const towerIndexes = { SOUTH: 0, NORTH: 0 };
  return connectionNodePairs
    .filter(pair => (
      Number.isInteger(pair.nodeI)
      && Number.isInteger(pair.nodeJ)
      && pair.nodeI > 0
      && pair.nodeJ > 0
      && pair.nodeI !== pair.nodeJ
    ))
    .map((pair, index) => {
      towerIndexes[pair.tower] += 1;
      const towerCode = pair.tower === "SOUTH" ? "S" : "N";
      return {
        damperId: `${towerCode}D${String(towerIndexes[pair.tower]).padStart(2, "0")}`,
        materialType,
        placementLabel: pair.label || `${pair.tower === "SOUTH" ? "南塔" : "北塔"}节点 ${pair.nodeI}-${pair.nodeJ}`,
        elementType: "USER300" as const,
        elementId: 9301 + index,
        nodeI: pair.nodeI,
        nodeJ: pair.nodeJ,
        direction,
        source: "USER_DEFINED" as const
      };
    });
};

const hasValidDamperConnectionNodes = (pairs: DamperConnectionNodePair[]) => (
  pairs.length > 0 && pairs.every(pair => (
    Number.isInteger(pair.nodeI)
    && Number.isInteger(pair.nodeJ)
    && pair.nodeI > 0
    && pair.nodeJ > 0
    && pair.nodeI !== pair.nodeJ
  ))
);

