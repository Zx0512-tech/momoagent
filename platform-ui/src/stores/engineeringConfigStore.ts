const normalizeRehydratedState = (state: EngineeringConfigState) => {
  const connectionNodePairs = state.damperBaseConfig.connectionNodePairs?.length
    ? state.damperBaseConfig.connectionNodePairs
    : defaultConnectionNodePairs;
  state.damperBaseConfig = {
    ...state.damperBaseConfig,
    connectionNodePairs,
    southTowerCount: connectionNodePairs.filter(pair => pair.tower === "SOUTH").length,
    northTowerCount: connectionNodePairs.filter(pair => pair.tower === "NORTH").length,
    damperInstanceRegistry: createDamperRegistry(
      state.damperBaseConfig.materialType,
      connectionNodePairs,
      state.damperBaseConfig.direction
    )
  };
  const normalizeMetric = (metric: ResultExtractionMetricConfig) => {
    const defaultMetric = DEFAULT_STRUCTURAL_RESULT_METRICS.find(item => item.id === metric.id);
    if (!defaultMetric) return metric;
    if (
      metric.id === "metric_beam_end_ux_cumulative" ||
      metric.id === "metric_tower_base_shear" ||
      metric.id === "metric_tower_base_moment"
    ) {
      return {
        ...metric,
        objectId: defaultMetric.objectId,
        statistic: defaultMetric.statistic,
        sourceDescription: defaultMetric.sourceDescription
      };
    }
    return metric;
  };

  const structuralMetrics = state.resultExtractionConfig.structuralMetrics.map(normalizeMetric);
  if (!structuralMetrics.some(metric => metric.id === "metric_beam_end_ux_cumulative")) {
    const cumulativeMetric = DEFAULT_STRUCTURAL_RESULT_METRICS.find(
      metric => metric.id === "metric_beam_end_ux_cumulative"
    );
    if (cumulativeMetric) {
      const insertIndex = structuralMetrics.findIndex(metric => metric.id === "metric_beam_end_ux_peak");
      structuralMetrics.splice(insertIndex >= 0 ? insertIndex + 1 : structuralMetrics.length, 0, cumulativeMetric);
    }
  }

  state.loadConfig = {
    ...state.loadConfig,
    earthquake: {
      ...state.loadConfig.earthquake,
      fileInput: {
        ...defaultLoadConfig.earthquake.fileInput,
        ...state.loadConfig.earthquake.fileInput
      },
      codeGeneration: {
        ...defaultLoadConfig.earthquake.codeGeneration,
        ...state.loadConfig.earthquake.codeGeneration
      }
    },
    wind: {
      ...state.loadConfig.wind,
      fileInput: {
        ...defaultLoadConfig.wind.fileInput,
        ...state.loadConfig.wind.fileInput
      },
      generated: {
        ...defaultLoadConfig.wind.generated,
        ...state.loadConfig.wind.generated
      }
    },
    traffic: {
      ...state.loadConfig.traffic,
      fileInput: {
        ...defaultLoadConfig.traffic.fileInput,
        ...state.loadConfig.traffic.fileInput
      },
      generated: {
        ...defaultLoadConfig.traffic.generated,
        ...state.loadConfig.traffic.generated
      }
    }
  };
  state.doeConfig = {
    ...state.doeConfig,
    sampleCount: state.doeConfig.sampleCount === 24 ? defaultDoeConfig.sampleCount : state.doeConfig.sampleCount,
    includeCorners: true,
    includeCenter: true,
    variables: state.doeConfig.variables.map(variable => {
      const defaultVariable = defaultDoeConfig.variables.find(item => item.id === variable.id);
      if (!defaultVariable) return variable;
      if (
        variable.id === "dampingCoefficient" &&
        variable.min === 600 &&
        variable.max === 2400
      ) {
        return { ...variable, min: defaultVariable.min, max: defaultVariable.max };
      }
      if (
        variable.id === "velocityExponent" &&
        variable.min === 0.2 &&
        variable.max === 0.8
      ) {
        return { ...variable, min: defaultVariable.min, max: defaultVariable.max };
      }
      return variable;
    })
  };
  state.solverBatchConfig = {
    ...state.solverBatchConfig,
    processCount: state.solverBatchConfig.processCount || defaultSolverBatchConfig.processCount,
    coresPerProcess: state.solverBatchConfig.coresPerProcess === 2
      ? defaultSolverBatchConfig.coresPerProcess
      : state.solverBatchConfig.coresPerProcess
  };
  state.surrogateLearningConfig = {
    ...state.surrogateLearningConfig,
    outputResponseIds: [...DEFAULT_OVERALL_TARGETS],
    modelFamilies: state.surrogateLearningConfig.modelFamilies
      .map(model => String(model) === "RSM" ? "RESPONSE_SURFACE" : model)
      .filter((model, index, models): model is SurrogateModelFamily => (
        EARTHQUAKE_SURROGATE_MODELS.includes(model as SurrogateModelFamily) &&
        models.indexOf(model) === index
      ))
  };
  if (state.surrogateLearningConfig.modelFamilies.length === 0) {
    state.surrogateLearningConfig.modelFamilies = EARTHQUAKE_SURROGATE_MODELS;
  }
  if (state.optimizationDecisionConfig.objectiveMode !== "CUSTOM") {
    const objectives = getOptimizationTargetsByMode(state.optimizationDecisionConfig.objectiveMode)
      .map(name => ({ name, direction: "MIN" as const }));
    state.optimizationDecisionConfig = {
      ...state.optimizationDecisionConfig,
      objectives,
      constraints: state.optimizationDecisionConfig.constraints.filter(constraint => (
        objectives.some(objective => objective.name === constraint.targetId)
      ))
    };
  }
  state.resultExtractionConfig = {
    ...state.resultExtractionConfig,
    structuralMetrics
  };
  state.moduleStatus = buildModuleStatus(state);
};

const initialConfig = createDefaultConfig();

export const useEngineeringConfigStore = create<EngineeringConfigState>()(
  persist(
    (set, get) => ({
      ...initialConfig,
      moduleStatus: buildModuleStatus(initialConfig),

      updateProjectConfig: patch => set(state => {
        const next = {
          ...state,
          projectConfig: {
            ...state.projectConfig,
            ...patch,
            modelFile: patch.modelFile
              ? { ...state.projectConfig.modelFile, ...patch.modelFile }
              : state.projectConfig.modelFile
          }
        };
        return withStatus(next);
      }),

      updateGlobalTaskConfig: patch => set(state => {
        const next = {
          ...state,
          globalTaskConfig: { ...state.globalTaskConfig, ...patch },
          solverBatchConfig: patch.solver
            ? { ...state.solverBatchConfig, solver: patch.solver, validated: false }
            : state.solverBatchConfig
        };
        return withStatus(next);
      }),

      updateDamperBaseConfig: patch => set(state => withStatus(regenerateDamperDerivedState(state, patch))),

      updateLoadConfig: patch => set(state => {
        const next = { ...state, loadConfig: { ...state.loadConfig, ...patch } };
        return withStatus(next);
      }),

      updateDoeConfig: patch => set(state => {
        const next = { ...state, doeConfig: { ...state.doeConfig, ...patch } };
        return withStatus(next);
      }),

      updateSolverBatchConfig: patch => set(state => {
        const next = { ...state, solverBatchConfig: { ...state.solverBatchConfig, ...patch } };
        return withStatus(next);
      }),

      updateResultExtractionConfig: patch => set(state => {
        const next = { ...state, resultExtractionConfig: { ...state.resultExtractionConfig, ...patch } };
        return withStatus(next);
      }),

      updateSurrogateLearningConfig: patch => set(state => {
        const next = { ...state, surrogateLearningConfig: { ...state.surrogateLearningConfig, ...patch } };
        return withStatus(next);
      }),

      updateOptimizationDecisionConfig: patch => set(state => {
        const next = { ...state, optimizationDecisionConfig: { ...state.optimizationDecisionConfig, ...patch } };
        return withStatus(next);
      }),

      validateModule: moduleId => set(state => {
        const next: EngineeringProjectConfig = { ...state };
        if (moduleId === "DOE") next.doeConfig = { ...state.doeConfig, validated: true };
        if (moduleId === "DAMPER_BASE") {
          next.damperBaseConfig = {
            ...state.damperBaseConfig,
            placementValidated: hasValidDamperConnectionNodes(state.damperBaseConfig.connectionNodePairs)
          };
        }
        if (moduleId === "LOADS") {
          const scenario = state.globalTaskConfig.scenario;
          next.loadConfig = {
            ...state.loadConfig,
            earthquake: scenario === "EARTHQUAKE"
              ? { ...state.loadConfig.earthquake, configured: true, validated: true }
              : state.loadConfig.earthquake,
            wind: scenario === "WIND" || scenario === "WIND_TRAFFIC"
              ? { ...state.loadConfig.wind, configured: true, validated: true }
              : state.loadConfig.wind,
            traffic: scenario === "TRAFFIC" || scenario === "WIND_TRAFFIC"
              ? { ...state.loadConfig.traffic, configured: true, validated: true }
              : state.loadConfig.traffic
          };
        }
        if (moduleId === "SOLVER_BATCH") next.solverBatchConfig = { ...state.solverBatchConfig, validated: true };
        if (moduleId === "RESULT_EXTRACTION") next.resultExtractionConfig = { ...state.resultExtractionConfig, validated: true };
        if (moduleId === "SURROGATE_LEARNING") next.surrogateLearningConfig = { ...state.surrogateLearningConfig, validated: true };
        if (moduleId === "OPTIMIZATION_DECISION") next.optimizationDecisionConfig = { ...state.optimizationDecisionConfig, validated: true };
        return withStatus(next);
      }),

      validateAllModules: () => {
        const current = get();
        getRequiredModules(current.globalTaskConfig.scenario, current.globalTaskConfig.executionTarget)
          .forEach(moduleId => get().validateModule(moduleId));
      },

      getModuleRoute: moduleId => get().moduleStatus.find(item => item.moduleId === moduleId)?.route ?? "/",
      getEngineeringConfig: () => engineeringConfigFromState(get())
    }),
    {
      name: "momo_engineering_config_v1",
      partialize: state => engineeringConfigFromState(state),
      onRehydrateStorage: () => state => {
        if (!state) return;
        normalizeRehydratedState(state);
      }
    }
  )
);

