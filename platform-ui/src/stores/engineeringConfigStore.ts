const getRequiredModules = (
  scenario: AnalysisScenarioType,
  target: TaskExecutionTarget
): EngineeringModuleId[] => {
  const required = new Set<EngineeringModuleId>(["DAMPER_BASE", "DOE"]);
  if (target !== "DESIGN_SAMPLES") required.add("LOADS");
  if (["BATCH_SOLVE", "RESULT_EXTRACTION", "SURROGATE_TRAINING", "OPTIMIZATION_DECISION"].includes(target)) {
    required.add("SOLVER_BATCH");
    required.add("RESULT_EXTRACTION");
  }
  if (target === "SURROGATE_TRAINING" || target === "OPTIMIZATION_DECISION") {
    required.add("SURROGATE_LEARNING");
  }
  if (target === "OPTIMIZATION_DECISION") required.add("OPTIMIZATION_DECISION");
  if (scenario && target === "COMMAND_STREAM") required.add("LOADS");
  return Array.from(required);
};

const loadRouteForScenario = (scenario: AnalysisScenarioType, loadConfig: EngineeringLoadConfig) => {
  if (scenario === "EARTHQUAKE") return "/loads?tab=earthquake";
  if (scenario === "WIND") return "/loads?tab=wind";
  if (scenario === "TRAFFIC") return "/loads?tab=traffic";
  if (!loadConfig.wind.configured) return "/loads?tab=wind";
  return "/loads?tab=traffic";
};

const evaluateLoadStatus = (
  scenario: AnalysisScenarioType,
  loadConfig: EngineeringLoadConfig
): { status: ModuleStatusKind; message: string; route: string } => {
  if (scenario === "EARTHQUAKE") {
    if (!loadConfig.earthquake.configured) {
      return { status: "UNCONFIGURED", message: "地震荷载未配置，点击前往配置", route: "/loads?tab=earthquake" };
    }
    return {
      status: loadConfig.earthquake.validated ? "VALIDATED" : "CONFIGURED",
      message: "地震荷载已配置",
      route: "/loads?tab=earthquake"
    };
  }
  if (scenario === "WIND") {
    if (!loadConfig.wind.configured) {
      return { status: "UNCONFIGURED", message: "风荷载未配置，点击前往配置", route: "/loads?tab=wind" };
    }
    return {
      status: loadConfig.wind.validated ? "VALIDATED" : "CONFIGURED",
      message: "风荷载已配置",
      route: "/loads?tab=wind"
    };
  }
  if (scenario === "TRAFFIC") {
    if (!loadConfig.traffic.configured) {
      return { status: "UNCONFIGURED", message: "车流荷载未配置，点击前往配置", route: "/loads?tab=traffic" };
    }
    return {
      status: loadConfig.traffic.validated ? "VALIDATED" : "CONFIGURED",
      message: "车流荷载已配置",
      route: "/loads?tab=traffic"
    };
  }

  if (!loadConfig.wind.configured && !loadConfig.traffic.configured) {
    return { status: "UNCONFIGURED", message: "风荷载与车流荷载均未配置", route: "/loads?tab=wind" };
  }
  if (!loadConfig.wind.configured) {
    return { status: "INCOMPLETE", message: "风-车组合缺少风荷载配置", route: "/loads?tab=wind" };
  }
  if (!loadConfig.traffic.configured) {
    return { status: "INCOMPLETE", message: "风-车组合缺少车流荷载配置", route: "/loads?tab=traffic" };
  }
  return {
    status: loadConfig.wind.validated && loadConfig.traffic.validated ? "VALIDATED" : "CONFIGURED",
    message: "风荷载和车流荷载已配置",
    route: loadRouteForScenario(scenario, loadConfig)
  };
};

const buildModuleStatus = (config: EngineeringProjectConfig): ModuleStatus[] => {
  const requiredModules = getRequiredModules(
    config.globalTaskConfig.scenario,
    config.globalTaskConfig.executionTarget
  );
  const requiredSet = new Set(requiredModules);
  const loadStatus = evaluateLoadStatus(config.globalTaskConfig.scenario, config.loadConfig);

  const moduleEvaluators: Record<EngineeringModuleId, () => Pick<ModuleStatus, "status" | "message" | "route">> = {
    DOE: () => ({
      status: config.doeConfig.variables.some(item => item.enabled) && config.doeConfig.sampleCount > 0
        ? config.doeConfig.validated ? "VALIDATED" : "CONFIGURED"
        : "UNCONFIGURED",
      message: config.doeConfig.variables.some(item => item.enabled)
        ? `已选择 ${config.doeConfig.variables.filter(item => item.enabled).length} 个 DOE 变量`
        : "未选择 DOE 设计变量",
      route: "/experiment-design"
    }),
    DAMPER_BASE: () => {
      const hasValidNodes = hasValidDamperConnectionNodes(config.damperBaseConfig.connectionNodePairs);
      const hasRegistry = config.damperBaseConfig.damperInstanceRegistry.length > 0;
      if (config.projectConfig.modelFile.parseStatus !== "PARSED") {
        return { status: "INCOMPLETE", message: "模型文件尚未解析，无法生成阻尼器注册表", route: "/damper-base" };
      }
      if (!hasRegistry) {
        return { status: "UNCONFIGURED", message: "未生成阻尼器实例注册表", route: "/damper-base" };
      }
      if (!hasValidNodes) {
        return { status: "INCOMPLETE", message: "自定义连接节点必须为不同的正整数节点", route: "/damper-base" };
      }
      return {
        status: config.damperBaseConfig.placementValidated ? "VALIDATED" : "CONFIGURED",
        message: `已按自定义节点注册 ${config.damperBaseConfig.damperInstanceRegistry.length} 个 USER300 阻尼器`,
        route: "/damper-base"
      };
    },
    LOADS: () => loadStatus,
    SOLVER_BATCH: () => ({
      status: config.solverBatchConfig.processCount > 0 && config.solverBatchConfig.coresPerProcess > 0
        ? config.solverBatchConfig.validated ? "VALIDATED" : "CONFIGURED"
        : "INCOMPLETE",
      message: `${config.solverBatchConfig.batchMode === "PARALLEL" ? "并行" : "串行"}：${config.solverBatchConfig.processCount} 进程，每进程 ${config.solverBatchConfig.coresPerProcess} 核`,
      route: "/solver"
    }),
    RESULT_EXTRACTION: () => {
      const enabledStructural = config.resultExtractionConfig.structuralMetrics.filter(item => item.enabled).length;
      const enabledDamper = config.resultExtractionConfig.autoDamperMetrics.filter(item => item.enabled).length;
      if (enabledStructural === 0 && enabledDamper === 0) {
        return { status: "UNCONFIGURED", message: "尚未启用任何结果提取指标", route: "/results" };
      }
      return {
        status: config.resultExtractionConfig.validated ? "VALIDATED" : "CONFIGURED",
        message: `结构指标 ${enabledStructural} 项，阻尼器自动指标 ${enabledDamper} 项`,
        route: "/results"
      };
    },
    SURROGATE_LEARNING: () => ({
      status: config.surrogateLearningConfig.modelFamilies.length > 0 && config.surrogateLearningConfig.outputResponseIds.length > 0
        ? config.surrogateLearningConfig.validated ? "VALIDATED" : "CONFIGURED"
        : "UNCONFIGURED",
      message: `代理模型：${config.surrogateLearningConfig.modelFamilies.join(", ")}`,
      route: "/surrogate"
    }),
    OPTIMIZATION_DECISION: () => ({
      status: config.optimizationDecisionConfig.objectives.length > 0
        ? config.optimizationDecisionConfig.validated ? "VALIDATED" : "CONFIGURED"
        : "UNCONFIGURED",
      message: `目标 ${config.optimizationDecisionConfig.objectives.length} 项，决策方法 ${config.optimizationDecisionConfig.decisionMethods.length} 项`,
      route: "/optimization"
    })
  };

  return MODULE_CATALOG.map(item => {
    const evaluated = moduleEvaluators[item.moduleId]();
    return {
      ...item,
      ...evaluated,
      required: requiredSet.has(item.moduleId)
    };
  });
};

const regenerateDamperDerivedState = (
  config: EngineeringProjectConfig,
  patch: Partial<DamperBaseConfig>
): EngineeringProjectConfig => {
  const nextDamper = { ...config.damperBaseConfig, ...patch };
  const connectionNodePairs = nextDamper.connectionNodePairs;
  const registry = createDamperRegistry(
    nextDamper.materialType,
    connectionNodePairs,
    nextDamper.direction
  );
  const nextConfig: EngineeringProjectConfig = {
    ...config,
    damperBaseConfig: {
      ...nextDamper,
      southTowerCount: connectionNodePairs.filter(pair => pair.tower === "SOUTH").length,
      northTowerCount: connectionNodePairs.filter(pair => pair.tower === "NORTH").length,
      damperInstanceRegistry: registry,
      placementValidated: patch.placementValidated ?? false
    },
    doeConfig: {
      ...config.doeConfig,
      variables: getExperimentDesignVariablesForMaterial(nextDamper.materialType),
      validated: false
    },
    resultExtractionConfig: {
      ...config.resultExtractionConfig,
      autoDamperMetrics: createAutoDamperMetrics(registry),
      validated: false
    }
  };
  return nextConfig;
};

